// Compiles the toolso template stylesheet with Tailwind into a committed static asset.
// `--check` regenerates into memory and fails when the committed file is stale.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

const output = resolve("src/ui/generated/toolso.css");
const dir = mkdtempSync(join(tmpdir(), "toolso-css-"));
try {
  const target = join(dir, "toolso.css");
  execFileSync(
    resolve("node_modules/.bin/tailwindcss"),
    [
      "-c",
      "tailwind.toolso.config.cjs",
      "-i",
      "src/templates/toolso/styles.css",
      "-o",
      target,
      "--minify",
    ],
    { stdio: ["ignore", "ignore", "pipe"], env: { ...process.env, BROWSERSLIST_IGNORE_OLD_DATA: "1" } },
  );
  const css =
    "/* Generated by scripts/build-toolso-css.mjs from src/templates/toolso. Do not edit. */\n" +
    readFileSync(target, "utf8").trimEnd() +
    "\n";
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(output, "utf8");
    } catch {}
    if (current !== css) {
      console.error("src/ui/generated/toolso.css is stale; run pnpm build:css");
      process.exit(1);
    }
  } else {
    writeFileSync(output, css);
    console.log(`Wrote ${output} (${css.length} bytes)`);
  }
} finally {
  rmSync(dir, { recursive: true, force: true });
}
